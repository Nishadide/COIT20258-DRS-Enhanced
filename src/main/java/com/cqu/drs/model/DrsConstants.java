package com.cqu.drs.model;

/**
 * Validation limits shared by the domain classes and the service layer.
 * Holding them in one place means a rule is never stated in two places and
 * cannot drift out of step between the two.
 */
public final class DrsConstants {

    /** Not instantiable: this class holds constants only. */
    private DrsConstants() {
    }

    // Coordinate ranges
    public static final double MIN_LATITUDE = -90.0;
    public static final double MAX_LATITUDE = 90.0;
    public static final double MIN_LONGITUDE = -180.0;
    public static final double MAX_LONGITUDE = 180.0;

    // Text field lengths
    public static final int ADDRESS_MIN_LENGTH = 1;
    public static final int ADDRESS_MAX_LENGTH = 200;
    public static final int DESCRIPTION_MAX_LENGTH = 500;
    public static final int ASSESSMENT_NOTES_MAX_LENGTH = 500;
    public static final int STATUS_NOTE_MAX_LENGTH = 200;
    public static final int ALERT_MESSAGE_MIN_LENGTH = 1;
    public static final int ALERT_MESSAGE_MAX_LENGTH = 300;
    public static final int AFFECTED_AREA_MIN_LENGTH = 1;
    public static final int AFFECTED_AREA_MAX_LENGTH = 200;

    // Account rules
    public static final int USERNAME_MIN_LENGTH = 3;
    public static final int USERNAME_MAX_LENGTH = 20;
    public static final int PASSWORD_MIN_LENGTH = 8;
    public static final int FULL_NAME_MIN_LENGTH = 1;
    public static final int FULL_NAME_MAX_LENGTH = 100;

    // Contact number rules
    public static final int CONTACT_MIN_DIGITS = 8;
    public static final int CONTACT_MAX_DIGITS = 15;

    // Reference numbers take the form DR-0001
    public static final String REFERENCE_PREFIX = "DR-";
    public static final String REFERENCE_PATTERN = "DR-\\d{4}";

    // Prefixes for the identifiers generated by the services
    public static final String TASK_PREFIX = "RT-";
    public static final String ALERT_PREFIX = "AL-";
    public static final String REPORTER_PREFIX = "RP-";
    public static final String COORDINATOR_PREFIX = "EC-";

    /** Characters taken from a generated UUID when forming a short identifier. */
    public static final int SHORT_ID_LENGTH = 8;

    /** Characters taken from a user identifier when forming a coordinator code. */
    public static final int COORDINATOR_CODE_LENGTH = 4;

    /** Default radius in kilometres used when searching for nearby reports. */
    public static final double DEFAULT_NEARBY_RADIUS_KM = 5.0;

    /** Mean radius of the Earth in kilometres, used by the distance calculation. */
    public static final double EARTH_RADIUS_KM = 6371.0;
}
