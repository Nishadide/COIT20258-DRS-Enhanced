package com.cqu.drs.repository;

import com.cqu.drs.model.DisasterReport;

import java.util.List;
import java.util.Optional;

/**
 * Stores disaster reports. A report is kept with its assessment, its response
 * tasks and its alerts attached, because none of those has meaning apart from
 * the report they belong to.
 *
 * This is an interface so that the storage technology can be replaced without
 * touching the services above it. DRS-Initial stored reports as JSON files;
 * DRS-Enhanced stores them in MySQL, and the services are unaware of either.
 */
public interface DisasterReportRepository {

    /**
     * Every report held.
     *
     * @return the reports
     */
    List<DisasterReport> findAll();

    /**
     * Finds one report by its reference number.
     *
     * @param reference the reference to look for, of the form DR-nnnn
     * @return the report, or an empty Optional when none matches
     */
    Optional<DisasterReport> findByReference(String reference);

    /**
     * Saves a report, replacing any earlier version of the same one.
     *
     * Used for a report that already exists and has changed: one that has been
     * assessed, had work dispatched, or been resolved.
     *
     * @param report the report to save
     */
    void save(DisasterReport report);

    /**
     * Stores a report that must not already exist.
     *
     * This is separate from {@link #save} because the two mean different
     * things, and only one method cannot tell them apart.
     *
     * <p>In DRS-Initial it did not matter. One user at one keyboard generated
     * one reference at a time, so a reference was never claimed twice and
     * save-or-update was always the right behaviour.
     *
     * <p>With a server handling several clients at once it matters a great
     * deal. References are generated by counting the reports already stored,
     * so two clients lodging a report at the same moment can both arrive at
     * DR-0005. If storing the second one were treated as an update, it would
     * overwrite the first, and a reported disaster would disappear with
     * nothing recorded anywhere. Using this method for a new report turns that
     * silent loss into a refusal the caller can act on, by taking the next
     * free reference and trying again.
     *
     * @param report the report to store
     * @throws DuplicateReferenceException when another report already holds
     *         this reference
     */
    void insert(DisasterReport report);

    /**
     * How many reports are held, used to generate the next reference number.
     *
     * @return the count
     */
    int count();
}
